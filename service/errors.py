"""Доменные исключения слоя сервиса.

Ошибки самой модели (`LLMError`, `ParseError`) определены в llm-слое (`llm/base.py`) —
сервис их не переопределяет, а пробрасывает наружу: бот различает «плохой ввод»,
«модель не отдала валидный ответ» и «сбой API» и показывает разные сообщения.
"""

from __future__ import annotations


class ScreenerError(Exception):
    """Базовое доменное исключение сервиса."""


class InputValidationError(ScreenerError):
    """Невалидный пользовательский ввод (пустой или слишком длинный)."""
